function validDate(value) {
  if (value === null || value === undefined) return null
  if (typeof value === "string" && value.trim() === "") return null
  const date = value instanceof Date ? value : new Date(value)
  return Number.isNaN(date.getTime()) ? null : date
}

/** @param {string | number | Date | null | undefined} value @param {string} lang */
export function formatAdminDate(value, lang) {
  const date = validDate(value)
  if (!date) return "—"
  return new Intl.DateTimeFormat(dateLocale(lang), {
    year: "numeric",
    month: "short",
    day: "numeric",
    timeZone: "UTC",
  }).format(date)
}

/** @param {string | number | Date | null | undefined} value @param {string} lang */
export function formatAdminDateTime(value, lang) {
  const date = validDate(value)
  if (!date) return "—"
  return new Intl.DateTimeFormat(dateLocale(lang), {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "UTC",
  }).format(date)
}

/** @param {string | number | Date | null | undefined} value @param {string} lang */
export function formatAdminRelative(value, lang) {
  const date = validDate(value)
  if (!date) return "—"
  const elapsedSeconds = Math.round((date.getTime() - Date.now()) / 1000)
  const absoluteSeconds = Math.abs(elapsedSeconds)
  /** @type {Array<[number, Intl.RelativeTimeFormatUnit, number]>} */
  const units = [
    [60, "second", 1],
    [60 * 60, "minute", 60],
    [24 * 60 * 60, "hour", 60 * 60],
    [30 * 24 * 60 * 60, "day", 24 * 60 * 60],
    [365 * 24 * 60 * 60, "month", 30 * 24 * 60 * 60],
    [Infinity, "year", 365 * 24 * 60 * 60],
  ]
  const unitInfo = units.find(([limit]) => absoluteSeconds < limit)
  if (!unitInfo) return "—"
  const [, unit, divisor] = unitInfo
  const amount = Math.round(elapsedSeconds / divisor)
  return new Intl.RelativeTimeFormat(dateLocale(lang), { numeric: "auto" }).format(amount, unit)
}
