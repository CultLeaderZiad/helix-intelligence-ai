const dateLocale = (lang) => (lang === "ar" ? "ar" : "en")

/** @param {string} lang @param {string} message @param {Record<string, string | number>} [values] */
export function adminMessage(lang, message, values = {}) {
  const template = lang === "ar" ? (arabicMessages[message] || message) : message
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  )
}

/** @param {string | null | undefined} status @param {boolean} [hasWorkspace] @param {string} lang */
export function adminAccessLabel(lang, status, hasWorkspace = true) {
  if (!hasWorkspace) return adminMessage(lang, "No workspace")
  const key = status ? accessStatusLabels[status.toLowerCase()] : undefined
  return key ? adminMessage(lang, key) : adminMessage(lang, "Access status unavailable")
}

/** @param {object | null | undefined} record */
export function getAdminAccessStatus(record) {
  if (!record) return null
  const row = /** @type {{ access_status?: string | null, access?: { status?: string | null } | null }} */ (record)
  return row.access_status ?? row.access?.status ?? null
}

