/** @typedef {{lang: string, setLang: (value: string | ((previous: string) => string)) => void, t: (key: string, fallback?: string) => string, toggleLanguage: () => void, isRtl: boolean}} LanguageContextValue */

/** @type {(key: string, fallback?: string) => string} */
const defaultTranslate = (key, fallback) => fallback || key

/** @type {import("react").Context<LanguageContextValue>} */
const LanguageContext = createContext({
  lang: "en",
  setLang: () => {},
  t: defaultTranslate,
  toggleLanguage: () => {},
  isRtl: false,
})

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem("helix_lang") || "en"
  })

  useEffect(() => {
    localStorage.setItem("helix_lang", lang)
    document.documentElement.lang = lang
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr"
  }, [lang])

  const t = (key, fallback = "") => {
    return translations[lang]?.[key] || fallback || key
  }

  const toggleLanguage = () => {
    setLang((prev) => (prev === "en" ? "ar" : "en"))
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, toggleLanguage, isRtl: lang === "ar" }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    return {
      lang: "en",
      setLang: () => {},
      t: (k, fallback) => fallback || k,
      toggleLanguage: () => {},
      isRtl: false,
    }
  }
  return context
}

export default LanguageContext
